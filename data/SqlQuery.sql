    -- 1. DANH MUC
    CREATE TABLE DanhMuc (
        maDanhMuc VARCHAR(20) NOT NULL PRIMARY KEY,
        tenDanhMuc NVARCHAR(100) NOT NULL,
        CONSTRAINT CK_DanhMuc_Ten CHECK (LEN(LTRIM(RTRIM(tenDanhMuc))) > 0)
    );

    -- 2. THUONG HIEU
    CREATE TABLE ThuongHieu (
        maThuongHieu VARCHAR(20) NOT NULL PRIMARY KEY,
        tenThuongHieu NVARCHAR(100) NOT NULL,
        CONSTRAINT CK_ThuongHieu_Ten CHECK (LEN(LTRIM(RTRIM(tenThuongHieu))) > 0)
    );

    -- 3. NHAN VIEN
    CREATE TABLE NhanVien (
        maNhanVien VARCHAR(20) NOT NULL PRIMARY KEY,
        tenNhanVien NVARCHAR(100) NOT NULL,
        soDienThoai VARCHAR(10) NOT NULL UNIQUE,
        hoatDong BIT NOT NULL CONSTRAINT DF_NhanVien_HoatDong DEFAULT 1,
        CONSTRAINT CK_NhanVien_Ten CHECK (LEN(LTRIM(RTRIM(tenNhanVien))) > 0),
        CONSTRAINT CK_NhanVien_SDT CHECK (
            DATALENGTH(soDienThoai)=10 AND LEFT(soDienThoai,1)='0'
            AND soDienThoai COLLATE Latin1_General_BIN2 NOT LIKE '%[^0-9]%'
        )
    );

    -- 4. TAI KHOAN (1 nhan vien toi da 1 tai khoan)
    CREATE TABLE TaiKhoan (
        maNhanVien VARCHAR(20) NOT NULL PRIMARY KEY,
        tenDangNhap VARCHAR(50) NOT NULL UNIQUE,
        taiKhoanHash VARCHAR(100) NOT NULL,
        CONSTRAINT FK_TaiKhoan_NhanVien FOREIGN KEY(maNhanVien) REFERENCES NhanVien(maNhanVien),
        CONSTRAINT CK_TaiKhoan_Ten CHECK (LEN(LTRIM(RTRIM(tenDangNhap)))>0),
        CONSTRAINT CK_TaiKhoan_MK CHECK (LEN(LTRIM(RTRIM(taiKhoanHash)))>0)
    );

    -- 5. KHACH HANG: KHONG CO KHACH LE
    CREATE TABLE KhachHang (
        maKH VARCHAR(20) NOT NULL PRIMARY KEY,
        tenKH NVARCHAR(100) NOT NULL,
        soDienThoai VARCHAR(10) NOT NULL UNIQUE,
        CONSTRAINT CK_KhachHang_Ten CHECK (LEN(LTRIM(RTRIM(tenKH)))>0),
        CONSTRAINT CK_KhachHang_SDT CHECK (
            DATALENGTH(soDienThoai)=10 AND LEFT(soDienThoai,1)='0'
            AND soDienThoai COLLATE Latin1_General_BIN2 NOT LIKE '%[^0-9]%'
        )
    );

    -- 6. NHA CUNG CAP
    CREATE TABLE NhaCungCap (
        maNCC VARCHAR(20) NOT NULL PRIMARY KEY,
        tenNCC NVARCHAR(100) NOT NULL,
        soDienThoai VARCHAR(10) NOT NULL UNIQUE,
        hoatDong BIT NOT NULL CONSTRAINT DF_NCC_HoatDong DEFAULT 1,
        CONSTRAINT CK_NCC_Ten CHECK (LEN(LTRIM(RTRIM(tenNCC)))>0),
        CONSTRAINT CK_NCC_SDT CHECK (
            DATALENGTH(soDienThoai)=10 AND LEFT(soDienThoai,1)='0'
            AND soDienThoai COLLATE Latin1_General_BIN2 NOT LIKE '%[^0-9]%'
        )
    );

    -- 7. SAN PHAM
    CREATE TABLE SanPham (
        maSP VARCHAR(20) NOT NULL PRIMARY KEY,
        maDanhMuc VARCHAR(20) NOT NULL,
        maThuongHieu VARCHAR(20) NOT NULL,
        tenSP NVARCHAR(300) NOT NULL,
        hoatDong BIT NOT NULL CONSTRAINT DF_SanPham_HoatDong DEFAULT 1,
        giaBan DECIMAL(18,2) NOT NULL,
        CONSTRAINT FK_SP_DanhMuc FOREIGN KEY(maDanhMuc) REFERENCES DanhMuc(maDanhMuc),
        CONSTRAINT FK_SP_ThuongHieu FOREIGN KEY(maThuongHieu) REFERENCES ThuongHieu(maThuongHieu),
        CONSTRAINT CK_SP_Ten CHECK(LEN(LTRIM(RTRIM(tenSP)))>0),
        CONSTRAINT CK_SP_Gia CHECK(giaBan>0)
    );

    -- 8. CHI TIET SAN PHAM: kichCo FLOAT theo so do va Entity Java (double)
    CREATE TABLE ChiTietSanPham (
        maCTSP VARCHAR(20) NOT NULL PRIMARY KEY,
        maSP VARCHAR(20) NOT NULL,
        kichCo FLOAT NOT NULL,
        mauSac NVARCHAR(50) NOT NULL,
        soLuongTon INT NOT NULL CONSTRAINT DF_CTSP_Ton DEFAULT 0,
        hoatDong BIT NOT NULL CONSTRAINT DF_CTSP_HoatDong DEFAULT 1,
        CONSTRAINT FK_CTSP_SP FOREIGN KEY(maSP) REFERENCES SanPham(maSP),
        CONSTRAINT UQ_CTSP_BienThe UNIQUE(maSP,kichCo,mauSac),
        CONSTRAINT CK_CTSP_Size CHECK(kichCo>0),
        CONSTRAINT CK_CTSP_Mau CHECK(LEN(LTRIM(RTRIM(mauSac)))>0),
        CONSTRAINT CK_CTSP_Ton CHECK(soLuongTon>=0)
    );

    -- 9. HOA DON (maKH NOT NULL theo yeu cau khong chap nhan khach le)
    CREATE TABLE HoaDon (
        maHD VARCHAR(20) NOT NULL PRIMARY KEY,
        maNhanVien VARCHAR(20) NOT NULL,
        maKH VARCHAR(20) NOT NULL,
        ngayLap DATETIME2 NOT NULL CONSTRAINT DF_HD_Ngay DEFAULT SYSDATETIME(),
        phuongThucThanhToan NVARCHAR(30) NOT NULL,
        thue DECIMAL(5,2) NOT NULL CONSTRAINT DF_HD_Thue DEFAULT 8,
        tongTien DECIMAL(18,2) NOT NULL,
        CONSTRAINT FK_HD_NV FOREIGN KEY(maNhanVien) REFERENCES NhanVien(maNhanVien),
        CONSTRAINT FK_HD_KH FOREIGN KEY(maKH) REFERENCES KhachHang(maKH),
        CONSTRAINT CK_HD_PTTT CHECK(phuongThucThanhToan IN (N'Tiền mặt',N'Chuyển khoản')),
        CONSTRAINT CK_HD_Thue CHECK(thue BETWEEN 0 AND 100),
        CONSTRAINT CK_HD_Tong CHECK(tongTien>=0)
    );

    -- 10. CHI TIET HOA DON
    CREATE TABLE ChiTietHoaDon (
        maHD VARCHAR(20) NOT NULL,
        maCTSP VARCHAR(20) NOT NULL,
        soLuong INT NOT NULL,
        donGia DECIMAL(18,2) NOT NULL,
        CONSTRAINT PK_CTHD PRIMARY KEY(maHD,maCTSP),
        CONSTRAINT FK_CTHD_HD FOREIGN KEY(maHD) REFERENCES HoaDon(maHD),
        CONSTRAINT FK_CTHD_CTSP FOREIGN KEY(maCTSP) REFERENCES ChiTietSanPham(maCTSP),
        CONSTRAINT CK_CTHD_SL CHECK(soLuong>0),
        CONSTRAINT CK_CTHD_DonGia CHECK(donGia>0)
    );

    -- 11. PHIEU NHAP
    CREATE TABLE PhieuNhap (
        maPN VARCHAR(20) NOT NULL PRIMARY KEY,
        maNCC VARCHAR(20) NOT NULL,
        maNhanVien VARCHAR(20) NOT NULL,
        ngayNhap DATETIME2 NOT NULL CONSTRAINT DF_PN_Ngay DEFAULT SYSDATETIME(),
        CONSTRAINT FK_PN_NCC FOREIGN KEY(maNCC) REFERENCES NhaCungCap(maNCC),
        CONSTRAINT FK_PN_NV FOREIGN KEY(maNhanVien) REFERENCES NhanVien(maNhanVien)
    );

    -- 12. CHI TIET PHIEU NHAP
    CREATE TABLE ChiTietPhieuNhap (
        maPN VARCHAR(20) NOT NULL,
        maCTSP VARCHAR(20) NOT NULL,
        soLuong INT NOT NULL,
        donGiaNhap DECIMAL(18,2) NOT NULL,
        CONSTRAINT PK_CTPN PRIMARY KEY(maPN,maCTSP),
        CONSTRAINT FK_CTPN_PN FOREIGN KEY(maPN) REFERENCES PhieuNhap(maPN),
        CONSTRAINT FK_CTPN_CTSP FOREIGN KEY(maCTSP) REFERENCES ChiTietSanPham(maCTSP),
        CONSTRAINT CK_CTPN_SL CHECK(soLuong>0),
        CONSTRAINT CK_CTPN_Gia CHECK(donGiaNhap>=0)
    );

    -- 13. PHIEU DOI TRA: hoaDonMoi NULL neu tra hang, co ma neu doi size
    -- trangThai trong Entity Java duoc suy ra tu hoaDonMoi, khong can cot SQL.
    CREATE TABLE PhieuDoiTra (
        maPDT VARCHAR(20) NOT NULL PRIMARY KEY,
        hoaDonGoc VARCHAR(20) NOT NULL,
        hoaDonMoi VARCHAR(20) NULL,
        maNhanVien VARCHAR(20) NOT NULL,
        ngayLap DATETIME2 NOT NULL CONSTRAINT DF_PDT_Ngay DEFAULT SYSDATETIME(),
        lyDo NVARCHAR(300) NOT NULL,
        CONSTRAINT FK_PDT_HDGoc FOREIGN KEY(hoaDonGoc) REFERENCES HoaDon(maHD),
        CONSTRAINT FK_PDT_HDMoi FOREIGN KEY(hoaDonMoi) REFERENCES HoaDon(maHD),
        CONSTRAINT FK_PDT_NV FOREIGN KEY(maNhanVien) REFERENCES NhanVien(maNhanVien),
        CONSTRAINT CK_PDT_HD CHECK(hoaDonMoi IS NULL OR hoaDonMoi<>hoaDonGoc),
        CONSTRAINT CK_PDT_LyDo CHECK(LEN(LTRIM(RTRIM(lyDo)))>0)
    );
    CREATE UNIQUE INDEX UQ_PDT_HDMoi ON PhieuDoiTra(hoaDonMoi)
        WHERE hoaDonMoi IS NOT NULL;

    -- 14. CHI TIET DOI TRA
    CREATE TABLE ChiTietDoiTra (
        maPDT VARCHAR(20) NOT NULL,
        maCTSP VARCHAR(20) NOT NULL,
        soLuong INT NOT NULL,
        soLuongNhapLai INT NOT NULL,
        CONSTRAINT PK_CTDT PRIMARY KEY(maPDT,maCTSP),
        CONSTRAINT FK_CTDT_PDT FOREIGN KEY(maPDT) REFERENCES PhieuDoiTra(maPDT),
        CONSTRAINT FK_CTDT_CTSP FOREIGN KEY(maCTSP) REFERENCES ChiTietSanPham(maCTSP),
        CONSTRAINT CK_CTDT_SL CHECK(soLuong>0),
        CONSTRAINT CK_CTDT_Nhap CHECK(soLuongNhapLai BETWEEN 0 AND soLuong)
    );

