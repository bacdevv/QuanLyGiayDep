WHERE hoaDonMoi IS NOT NULL;');

CREATE TABLE ChiTietDoiTra (
    maPDT VARCHAR(20) NOT NULL,
    maCTSP VARCHAR(20) NOT NULL,
    soLuong INT NOT NULL,
    soLuongNhapLai INT NOT NULL,
    PRIMARY KEY (maPDT, maCTSP),
    FOREIGN KEY (maPDT) REFERENCES PhieuDoiTra(maPDT),
    FOREIGN KEY (maCTSP) REFERENCES ChiTietSanPham(maCTSP),
    CHECK (soLuong > 0),
    CHECK (soLuongNhapLai >= 0 AND soLuongNhapLai <= soLuong)
);



