CREATE TABLE DanhMuc (
    maDanhMuc VARCHAR(20) NOT NULL PRIMARY KEY,
    tenDanhMuc NVARCHAR(100) NOT NULL,
    CHECK (LEN(LTRIM(RTRIM(tenDanhMuc))) > 0)
);

CREATE TABLE ThuongHieu (
    maThuongHieu VARCHAR(20) NOT NULL PRIMARY KEY,
    tenThuongHieu NVARCHAR(100) NOT NULL,
    CHECK (LEN(LTRIM(RTRIM(tenThuongHieu))) > 0)
);

CREATE TABLE NhanVien (
    maNhanVien VARCHAR(20) NOT NULL PRIMARY KEY,
    tenNhanVien NVARCHAR(100) NOT NULL,
    soDienThoai VARCHAR(15) NULL,
    hoatDong BIT NOT NULL DEFAULT 1,
    CHECK (LEN(LTRIM(RTRIM(tenNhanVien))) > 0)
);

CREATE TABLE TaiKhoan (
    maNhanVien VARCHAR(20) NOT NULL PRIMARY KEY,
    tenDangNhap VARCHAR(50) NOT NULL UNIQUE,
    taiKhoanHash VARCHAR(100) NOT NULL,
    FOREIGN KEY (maNhanVien) REFERENCES NhanVien(maNhanVien),
    CHECK (LEN(LTRIM(RTRIM(tenDangNhap))) > 0),
    CHECK (LEN(taiKhoanHash) > 0)
);

CREATE TABLE KhachHang (
    maKH VARCHAR(20) NOT NULL PRIMARY KEY,
    tenKH NVARCHAR(100) NOT NULL,
    soDienThoai VARCHAR(15) NULL,
    CHECK (LEN(LTRIM(RTRIM(tenKH))) > 0)
);

CREATE TABLE NhaCungCap (
    maNCC VARCHAR(20) NOT NULL PRIMARY KEY,
    tenNCC NVARCHAR(100) NOT NULL,
    soDienThoai VARCHAR(15) NULL,
    hoatDong BIT NOT NULL DEFAULT 1,
    CHECK (LEN(LTRIM(RTRIM(tenNCC))) > 0)
);

CREATE TABLE SanPham (
    maSP VARCHAR(20) NOT NULL PRIMARY KEY,
    maDanhMuc VARCHAR(20) NOT NULL,
    maThuongHieu VARCHAR(20) NOT NULL,
    tenSP NVARCHAR(300) NOT NULL,
    hoatDong BIT NOT NULL DEFAULT 1,
    giaBan DECIMAL(18,2) NOT NULL,
    FOREIGN KEY (maDanhMuc) REFERENCES DanhMuc(maDanhMuc),
    FOREIGN KEY (maThuongHieu) REFERENCES ThuongHieu(maThuongHieu),
    CHECK (LEN(LTRIM(RTRIM(tenSP))) > 0),
    CHECK (giaBan >= 0)
);

CREATE TABLE ChiTietSanPham (
    maCTSP VARCHAR(20) NOT NULL PRIMARY KEY,
    maSP VARCHAR(20) NOT NULL,
    kichCo VARCHAR(10) NOT NULL,
    mauSac NVARCHAR(50) NOT NULL,
    soLuongTon INT NOT NULL DEFAULT 0,
    hoatDong BIT NOT NULL DEFAULT 1,
    FOREIGN KEY (maSP) REFERENCES SanPham(maSP),
    UNIQUE (maSP, kichCo, mauSac),
    CHECK (LEN(LTRIM(RTRIM(kichCo))) > 0),
    CHECK (LEN(LTRIM(RTRIM(mauSac))) > 0),
    CHECK (soLuongTon >= 0)
);

CREATE TABLE HoaDon (
    maHD VARCHAR(20) NOT NULL PRIMARY KEY,
    maNhanVien VARCHAR(20) NOT NULL,
    maKH VARCHAR(20) NULL,
    ngayLap DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    phuongThucThanhToan NVARCHAR(30) NOT NULL,
    thue DECIMAL(5,2) NOT NULL DEFAULT 0,
    tongTien DECIMAL(18,2) NOT NULL,
    FOREIGN KEY (maNhanVien) REFERENCES NhanVien(maNhanVien),
    FOREIGN KEY (maKH) REFERENCES KhachHang(maKH),
    CHECK (phuongThucThanhToan IN (N'Tiền mặt', N'Chuyển khoản')),
    CHECK (thue >= 0 AND thue <= 100),
    CHECK (tongTien >= 0)
);

CREATE TABLE ChiTietHoaDon (
    maHD VARCHAR(20) NOT NULL,
    maCTSP VARCHAR(20) NOT NULL,
    soLuong INT NOT NULL,
    donGia DECIMAL(18,2) NOT NULL,
    PRIMARY KEY (maHD, maCTSP),
    FOREIGN KEY (maHD) REFERENCES HoaDon(maHD),
    FOREIGN KEY (maCTSP) REFERENCES ChiTietSanPham(maCTSP),
    CHECK (soLuong > 0),
    CHECK (donGia > 0)
);

CREATE TABLE PhieuNhap (
    maPN VARCHAR(20) NOT NULL PRIMARY KEY,
    maNCC VARCHAR(20) NOT NULL,
    maNhanVien VARCHAR(20) NOT NULL,
    ngayNhap DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    FOREIGN KEY (maNCC) REFERENCES NhaCungCap(maNCC),
    FOREIGN KEY (maNhanVien) REFERENCES NhanVien(maNhanVien)
);

CREATE TABLE ChiTietPhieuNhap (
    maPN VARCHAR(20) NOT NULL,
    maCTSP VARCHAR(20) NOT NULL,
    soLuong INT NOT NULL,
    donGiaNhap DECIMAL(18,2) NOT NULL,
    PRIMARY KEY (maPN, maCTSP),
    FOREIGN KEY (maPN) REFERENCES PhieuNhap(maPN),
    FOREIGN KEY (maCTSP) REFERENCES ChiTietSanPham(maCTSP),
    CHECK (soLuong > 0),
    CHECK (donGiaNhap >= 0)
);

CREATE TABLE PhieuDoiTra (
    maPDT VARCHAR(20) NOT NULL PRIMARY KEY,
    hoaDonGoc VARCHAR(20) NOT NULL,
    hoaDonMoi VARCHAR(20) NULL,
    maNhanVien VARCHAR(20) NOT NULL,
    ngayLap DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    lyDo NVARCHAR(300) NOT NULL,
    FOREIGN KEY (hoaDonGoc) REFERENCES HoaDon(maHD),
    FOREIGN KEY (hoaDonMoi) REFERENCES HoaDon(maHD),
    FOREIGN KEY (maNhanVien) REFERENCES NhanVien(maNhanVien),
    CHECK (hoaDonMoi IS NULL OR hoaDonMoi <> hoaDonGoc),
    CHECK (LEN(LTRIM(RTRIM(lyDo))) > 0)
);

EXEC(N'CREATE UNIQUE INDEX UQ_PhieuDoiTra_HoaDonMoi
